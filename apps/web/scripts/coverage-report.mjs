// The control coverage report (docs/test-suite-spec.md S1). Reads what the browser tests recorded
// (e2e/coverage.ts, run with E2E_COVERAGE=1) and the controls in the source, and writes
// docs/test-suite-coverage.md: per route, each control seen on screen, whether a test pressed it,
// and which tests; the controls with no accessible name; and the controls per source file.
//
//   E2E_COVERAGE=1 pnpm --filter @laststint/web e2e && pnpm --filter @laststint/web coverage:report

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = fileURLToPath(new URL('..', import.meta.url));
const IN = join(WEB, 'test-results', 'control-coverage');
const OUT = join(WEB, '..', '..', 'docs', 'test-suite-coverage.md');

const events = existsSync(IN)
  ? readdirSync(IN)
      .filter((f) => f.endsWith('.jsonl'))
      .flatMap((f) =>
        readFileSync(join(IN, f), 'utf8')
          .split('\n')
          .filter(Boolean)
          .map((l) => JSON.parse(l)),
      )
  : [];
if (!events.length) {
  console.error(`No coverage records in ${IN}: run the e2e suite with E2E_COVERAGE=1 first.`);
  process.exit(1);
}

/** route -> "role: name" -> { projects, used, tests } */
const routes = new Map();
const unnamed = new Map();
for (const e of events) {
  const key = `${e.role}: ${e.name || '(no name)'}`;
  if (!routes.has(e.route)) routes.set(e.route, new Map());
  const controls = routes.get(e.route);
  if (!controls.has(key)) controls.set(key, { projects: new Set(), used: false, tests: new Set() });
  const c = controls.get(key);
  c.projects.add(e.project);
  if (e.kind === 'used') {
    c.used = true;
    c.tests.add(`${e.spec}`);
  }
  if (e.unnamed)
    unnamed.set(`${e.route} · ${e.role}`, (unnamed.get(`${e.route} · ${e.role}`) ?? 0) + 1);
}

// The source side: controls per component file (a <button> in a list counts once).
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory()
      ? walk(join(dir, d.name))
      : d.name.endsWith('.tsx') && !d.name.includes('.test.')
        ? [join(dir, d.name)]
        : [],
  );
}
const count = (src, re) => (src.match(re) ?? []).length;
const files = walk(join(WEB, 'src'))
  .map((f) => {
    const src = readFileSync(f, 'utf8');
    return {
      file: relative(join(WEB, 'src'), f),
      buttons: count(src, /<button\b/g),
      inputs: count(src, /<(input|select|textarea)\b/g),
      links: count(src, /<a\s/g),
    };
  })
  .filter((f) => f.buttons + f.inputs + f.links > 0);

let seen = 0;
let used = 0;
const rows = [];
for (const [route, controls] of [...routes].sort(([a], [b]) => a.localeCompare(b))) {
  const list = [...controls].sort(([a], [b]) => a.localeCompare(b));
  const u = list.filter(([, c]) => c.used).length;
  seen += list.length;
  used += u;
  rows.push(`### \`${route}\` (${u} of ${list.length} pressed)\n`);
  rows.push('| Control | Pressed | On | Pressed by |', '|---|---|---|---|');
  for (const [key, c] of list)
    rows.push(
      `| ${key.replace(/\|/g, '\\|')} | ${c.used ? 'yes' : '**no**'} | ${[...c.projects].sort().join(', ')} | ${[...c.tests].sort().join(', ')} |`,
    );
  rows.push('');
}

const out = [
  '# Control coverage (generated)',
  '',
  'Generated by `apps/web/scripts/coverage-report.mjs` from an `E2E_COVERAGE=1` run of the browser',
  'tests (docs/test-suite-spec.md S1). A control is keyed by route, role and accessible name, the',
  'way `getByRole` finds it; numbers in names are `#`. "Pressed" means a test clicked, typed into or',
  'changed it. Controls a test never brings on screen are missing here; the source table at the',
  'end shows where they live.',
  '',
  `**${used} of ${seen} controls seen on screen are pressed by a test (${Math.round((100 * used) / seen)}%),`,
  `across ${routes.size} routes. ${[...unnamed.values()].reduce((a, b) => a + b, 0)} controls have no accessible name.**`,
  '',
  '## By route',
  '',
  ...rows,
  '## Controls with no accessible name (D7)',
  '',
  '| Where | Count |',
  '|---|---|',
  ...[...unnamed].sort().map(([k, n]) => `| ${k} | ${n} |`),
  '',
  '## Controls in the source, per file',
  '',
  `${files.length} files hold controls: ${files.reduce((a, f) => a + f.buttons, 0)} \`<button>\`, ${files.reduce((a, f) => a + f.inputs, 0)} inputs and ${files.reduce((a, f) => a + f.links, 0)} links (a control in a list counts once).`,
  '',
  '| File | Buttons | Inputs | Links |',
  '|---|---|---|---|',
  ...files
    .sort((a, b) => a.file.localeCompare(b.file))
    .map((f) => `| ${f.file} | ${f.buttons} | ${f.inputs} | ${f.links} |`),
  '',
];
writeFileSync(OUT, out.join('\n'));
console.log(
  `${used}/${seen} controls pressed across ${routes.size} routes -> ${relative(process.cwd(), OUT)}`,
);
