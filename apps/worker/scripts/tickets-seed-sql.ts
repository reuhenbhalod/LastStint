// Turn data/tickets.json's entries into INSERT statements (scripts/tickets-seed.ts writes them
// to data/tickets-seed.sql). No Node APIs here, so the Worker tests can run the SQL on a D1.
//
// Idempotent: each INSERT adds its ticket only if no ticket has that title yet, so seeding
// twice adds nothing the second time. (A seeded ticket renamed in the app would be added
// again under its old title.)

import { parseTicketInput } from '../src/ticketFields.js';

/**
 * A SQL string expression: single quotes doubled, and line breaks spelled char(13)/char(10) so
 * every statement stays on one line. NUL can't be stored as TEXT, so it's refused.
 */
export function sqlString(s: string): string {
  if (s.includes('\0')) throw new Error('text contains a NUL character');
  const quoted = `'${s.replace(/'/g, "''")}'`;
  return quoted.replace(/\r/g, "' || char(13) || '").replace(/\n/g, "' || char(10) || '");
}

/**
 * INSERTs for the seed tickets, checked like the API checks a new ticket. Throws, naming the
 * entry, on the first bad one or on a repeated title.
 */
export function seedSql(entries: unknown, now: number): string {
  if (!Array.isArray(entries)) throw new Error('tickets.json must be an array');
  const lines = [
    `-- Generated by scripts/tickets-seed.ts from data/tickets.json (${entries.length}).`,
  ];
  const titles = new Set<string>();
  entries.forEach((entry, i) => {
    const parsed = parseTicketInput(entry, true);
    if (!parsed.ok) throw new Error(`ticket ${i}: ${parsed.error}`);
    const t = parsed.value;
    const title = t.title ?? '';
    if (titles.has(title)) throw new Error(`ticket ${i}: repeats the title "${title}"`);
    titles.add(title);
    const status = t.status ?? 'open';
    const values = [
      sqlString(title),
      sqlString(t.description ?? ''),
      sqlString(t.category ?? 'other'),
      sqlString(status),
      sqlString(t.notes ?? ''),
      sqlString(t.source ?? ''),
      String(now),
      String(now),
      status === 'done' ? String(now) : 'NULL',
    ];
    lines.push(
      `INSERT INTO tickets (title, description, category, status, notes, source, created_at, updated_at, completed_at) SELECT ${values.join(', ')} WHERE NOT EXISTS (SELECT 1 FROM tickets WHERE title = ${sqlString(title)});`,
    );
  });
  return `${lines.join('\n')}\n`;
}
