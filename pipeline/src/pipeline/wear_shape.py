"""Quadratic tyre wear, pooled by track and era (Eras model fix S4).

The lap model's wear is linear per compound (fit.py: `wear x age`, plus a cliff kept only where
it lowers the race's BIC), so a stint that falls off late is run flat: Alonso's 32-lap softs at
Hungary 2014 lost about 1.1 s a lap over their last 7 laps against Rosberg's new ones, where
the race's linear SOFT wear (0.034 s a lap) gives 0.25. An Eras build adds a quadratic term per
dry compound, `degQuad x wear^2` in the sims, fitted with the rest of the model and shrunk to a
prior from the other races at the same track and era:

- **Measured** per race and compound (fit.measure_quad): the quadratic term fitted jointly with
  the race's lap model (ordered compounds and their priors, no cliffs), unshrunk and unbounded,
  with its standard error, on the clean laps of every timed, non-reconstructed race snapshot in
  data/raw (fitRaces). A race of short stints measures it with a large standard error.
- **Pooled** in two levels per era (the compound priors' eras) and compound, by random effects:
  `tau2` is the race-to-race variance of the term across the era (DerSimonian-Laird) and
  `tau2Within` its variance between races at one track layout (the same estimator on the
  deviations from each layout's mean, layouts with two races or more; overtaking.layout_of).
  The track level's own variance is `tau2 - tau2Within` (floored).
- **The prior** for race r (quad_priors): its layout's level estimated from the *other* races
  there (each at variance se^2 + tau2Within), shrunk to the era's mean with the track variance;
  sd = sqrt(that level's variance + tau2Within). A track with no other measured race gives the
  era's mean at sd sqrt(tau2). The race's fit then adds one prior row of weight noise / sd,
  noise being its own residual sd, so the posterior is the precision-weighted mix of its laps
  and the prior; the term is bounded at 0 (no tyre gets faster with age).

Gating: only an Eras build of a race with real timing (build.py's `eras_build and recon is
None`) passes priors, and only the file's compounds with a positive term carry `degQuad`; the
sims add it only when the file has it, so every Daily/Gauntlet file and every other build is
unchanged.

    uv run python -m pipeline.wear_shape [--cache DIR]   # remeasure, write config/wear_shape.json
"""

from __future__ import annotations

import json
import math
from functools import cache
from pathlib import Path

import numpy as np

from . import fit
from .overtaking import fit_races, layout_of
from .paths import CONFIG_DIR

WEAR_SHAPE_PATH = CONFIG_DIR / "wear_shape.json"
MIN_LAPS = 30  # clean laps on a compound before a race measures its term
TAU2_FLOOR = 1e-9  # (s/lap^2)^2: a variance estimated at 0 is floored here


def _dl_tau2(groups: list[list[tuple[float, float]]]) -> float:
    """DerSimonian-Laird between-unit variance, pooled over `groups` (each a list of (q, se)):
    the deviations are from each group's precision-weighted mean."""
    q_stat = dof = c = 0.0
    for g in groups:
        if len(g) < 2:
            continue
        w = np.array([1.0 / se**2 for _, se in g])
        q = np.array([v for v, _ in g])
        mean = float((w * q).sum() / w.sum())
        q_stat += float((w * (q - mean) ** 2).sum())
        dof += len(g) - 1
        c += float(w.sum() - (w**2).sum() / w.sum())
    if dof == 0 or c <= 0:
        return TAU2_FLOOR
    return max((q_stat - dof) / c, TAU2_FLOOR)


def pool(measured: dict[str, dict]) -> dict:
    """The table (WEAR_SHAPE_PATH) from each race's measurement: {race: {era, noise,
    compounds: {c: {q, se, laps, maxAge}}}}."""
    by_group: dict[tuple[str, str], list[tuple[str, str, float, float]]] = {}
    for race, m in measured.items():
        for c, v in m["compounds"].items():
            by_group.setdefault((m["era"], c), []).append(
                (race, layout_of(race) or race, v["q"], v["se"])
            )
    groups: dict[str, dict] = {}
    for (era, c), rows in sorted(by_group.items()):
        tau2 = _dl_tau2([[(q, se) for *_, q, se in rows]])
        layouts: dict[str, list[tuple[float, float]]] = {}
        for _, lay, q, se in rows:
            layouts.setdefault(lay, []).append((q, se))
        tau2_within = min(_dl_tau2(list(layouts.values())), tau2)
        w = np.array([1.0 / (se**2 + tau2) for *_, se in rows])
        q = np.array([v for *_, v, _ in rows])
        groups.setdefault(era, {})[c] = {
            "mean": float((w * q).sum() / w.sum()),
            "tau2": tau2,
            "tau2Within": tau2_within,
            "races": len(rows),
        }
    return {
        "_comment": (
            "Eras quadratic tyre wear (pipeline/src/pipeline/wear_shape.py; its docstring has the"
            " method). Generated by `python -m pipeline.wear_shape`; do not edit by hand. Per"
            " race and dry compound: the unshrunk quadratic wear term q (s per lap of tyre age"
            " squared) and its standard error; per era and compound: the random-effects mean,"
            " the race-to-race variance tau2 and the variance within a track layout tau2Within."
        ),
        "minLaps": MIN_LAPS,
        "groups": groups,
        "races": dict(sorted(measured.items())),
    }


@cache
def load_table(path: Path = WEAR_SHAPE_PATH) -> dict:
    return json.loads(Path(path).read_text())


def quad_priors(
    race_id: str, era: str, table: dict | None = None
) -> tuple[dict[str, fit.QuadPrior], str]:
    """The race's prior on each dry compound's quadratic wear term (fit.QuadPrior), and a build
    note. Its own measurement is left out of its prior (its laps count once, in its fit)."""
    table = table or load_table()
    groups = table["groups"].get(era) or {}
    me = table["races"].get(race_id) or {}
    layout = layout_of(race_id) or race_id
    noises = [r["noise"] for r in table["races"].values() if r.get("noise")]
    noise = float(me.get("noise") or np.median(noises))
    priors: dict[str, fit.QuadPrior] = {}
    parts = []
    for c, g in sorted(groups.items()):
        tau2, within = g["tau2"], g["tau2Within"]
        track = max(tau2 - within, TAU2_FLOOR)
        others = [
            r["compounds"][c]
            for rid, r in table["races"].items()
            if rid != race_id
            and r["era"] == era
            and c in r["compounds"]
            and (layout_of(rid) or rid) == layout
        ]
        precision = 1.0 / track + sum(1.0 / (o["se"] ** 2 + within) for o in others)
        level = (
            g["mean"] / track + sum(o["q"] / (o["se"] ** 2 + within) for o in others)
        ) / precision
        sd = math.sqrt(1.0 / precision + within)
        priors[c] = fit.QuadPrior(mean=max(level, 0.0), sd=sd, noise=noise)
        parts.append(f"{c} {level * 1000:.3f}±{sd * 1000:.3f} ms/lap² ({len(others)} at {layout})")
    note = "wear shape (S4): quadratic wear priors " + (", ".join(parts) or "none")
    return priors, note


def race_measure(race_id: str) -> dict | None:
    """One race's measurement (None: a race that doesn't build or has no dry compound)."""
    from . import build, faults, incidents

    try:
        res = build.build_race(race_id, wear_shape=False)
    except (ValueError, FileNotFoundError, KeyError):
        return None
    era = res.model["era"]
    facts, _ = faults.split_retired(res.laps, incidents.fault_facts(race_id))
    try:
        dry = build.dry_fit(race_id, res.laps, era, facts)
    except ValueError:
        return None
    from . import wet

    fixed = wet.FUEL_PRIOR if dry.wet else None
    measured, noise = fit.measure_quad(dry.clean, era, fixed, MIN_LAPS)
    if not measured:
        return None
    return {
        "era": era,
        "noise": round(noise, 4),
        "compounds": {
            c: {"q": m.q, "se": m.se, "laps": m.laps, "maxAge": m.max_age}
            for c, m in sorted(measured.items())
        },
    }


def main(argv: list[str] | None = None) -> None:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", type=Path, help="per-race measurement (json) cache dir")
    ap.add_argument("--out", type=Path, default=WEAR_SHAPE_PATH)
    args = ap.parse_args(argv)
    measured: dict[str, dict] = {}
    for race_id in fit_races():
        cached = args.cache / f"{race_id}.json" if args.cache else None
        if cached is not None and cached.exists():
            m = json.loads(cached.read_text())
        else:
            m = race_measure(race_id)
            if cached is not None:
                cached.parent.mkdir(parents=True, exist_ok=True)
                cached.write_text(json.dumps(m), encoding="utf-8", newline="\n")
        if m is None:
            print(f"{race_id}: left out (doesn't build, or no dry compound with {MIN_LAPS} laps)")
            continue
        measured[race_id] = m
        print(
            f"{race_id}: "
            + ", ".join(
                f"{c} {v['q'] * 1000:+.3f}±{v['se'] * 1000:.3f}" for c, v in m["compounds"].items()
            ),
            flush=True,
        )
    table = pool(measured)
    args.out.write_text(json.dumps(table, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    for era, cs in table["groups"].items():
        for c, g in cs.items():
            print(
                f"  {era} {c}: mean {g['mean'] * 1000:.3f} ms/lap²,"
                f" tau {math.sqrt(g['tau2']) * 1000:.3f},"
                f" within {math.sqrt(g['tau2Within']) * 1000:.3f} ({g['races']} races)"
            )


if __name__ == "__main__":
    main()
